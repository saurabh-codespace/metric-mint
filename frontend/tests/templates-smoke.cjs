const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');

(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const context = await browser.newContext({ viewport: { width: 1500, height: 1000 }, reducedMotion: 'reduce' });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const output = path.resolve(__dirname, '../test-results');
  await fs.mkdir(output, { recursive: true });
  const username = process.env.METRIC_MINT_TEST_USERNAME || 'admin';
  const password = process.env.METRIC_MINT_TEST_PASSWORD || 'admin';
  const auth = 'Basic ' + Buffer.from(`${username}:${password}`).toString('base64');
  const request = async (url, method = 'GET', body) => {
    const response = await fetch(`http://127.0.0.1:8090/api${url}`, {
      method, headers: { Authorization: auth, 'Content-Type': 'application/json' },
      body: body === undefined ? undefined : JSON.stringify(body),
    });
    assert.ok(response.ok, `${method} ${url}: ${response.status} ${response.ok ? '' : await response.text()}`);
    return response.status === 204 ? undefined : response.json();
  };
  const login = async target => {
    await target.getByLabel('Username', { exact: true }).fill(username);
    await target.getByLabel('Password', { exact: true }).fill(password);
    await target.getByRole('button', { name: 'Sign in', exact: true }).click();
  };
  const ids = [];
  let publicationId;
  try {
    await page.goto('http://127.0.0.1:5173');
    await login(page);
    await page.getByRole('button', { name: 'Overview', exact: true }).click();
    await page.getByRole('heading', { name: 'Invoice performance', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Reports', exact: true }).click();
    await page.getByRole('button', { name: 'Report templates', exact: true }).click();
    await page.getByRole('button', { name: 'Create template', exact: true }).click();
    const name = `Browser template ${Date.now()}`;
    await page.getByLabel('Report name', { exact: true }).fill(name);
    await page.getByRole('button', { name: 'Add area chart', exact: true }).dragTo(page.locator('.template-drop-target'), { targetPosition: { x: 100, y: 30 } });
    const editor = page.locator('.template-widget-editor').first();
    await editor.getByLabel('Widget title', { exact: true }).fill('Queue resolved');
    await editor.getByLabel('Data source', { exact: true }).selectOption('workbook:queue-management');
    await editor.getByLabel('Label field', { exact: true }).selectOption('date');
    await editor.getByLabel('Value field', { exact: true }).selectOption('resolved');
    await editor.getByLabel('Visualization', { exact: true }).selectOption('area');
    await page.locator('.template-visual-builder').scrollIntoViewIfNeeded();
    await page.getByRole('button', { name: 'Add table', exact: true }).dragTo(page.locator('.template-drop-target'), { targetPosition: { x: 100, y: 30 } });
    const tableEditor = page.locator('.template-widget-editor').nth(1);
    await tableEditor.getByLabel('Widget title', { exact: true }).fill('Utilization table');
    await tableEditor.getByLabel('Data source', { exact: true }).selectOption('workbook:utilization');
    await tableEditor.getByLabel('Visualization', { exact: true }).selectOption('table');
    await tableEditor.getByLabel('Width', { exact: true }).selectOption('full');
    await tableEditor.getByRole('checkbox', { name: 'Team', exact: true }).check();
    await tableEditor.getByRole('checkbox', { name: 'Utilization Percent', exact: true }).check();
    await page.getByRole('button', { name: 'Preview report', exact: true }).click();
    await page.locator('.template-result-widget').nth(1).waitFor();
    assert.equal(await page.locator('.template-result-widget tbody tr').count(), 8);
    await page.getByRole('button', { name: 'Drag Utilization table', exact: true }).dragTo(page.locator('.template-layout-tile').first());
    assert.equal(await page.locator('.template-result-widget').count(), 0, 'Rearranging clears stale preview');
    assert.equal(await page.locator('.template-layout-tile strong').first().textContent(), 'Utilization table');
    assert.equal(await page.locator('.template-widget-editor').first().getByLabel('Widget title', { exact: true }).inputValue(), 'Utilization table');
    await page.getByRole('button', { name: 'Drag Utilization table', exact: true }).evaluate(element => element.scrollIntoView({ block: 'center' }));
    await page.getByRole('button', { name: 'Drag Utilization table', exact: true }).dragTo(page.locator('.template-drop-target'), { targetPosition: { x: 100, y: 30 } });
    assert.equal(await page.locator('.template-layout-tile strong').first().textContent(), 'Queue resolved');
    await page.getByRole('button', { name: 'Move Utilization table earlier', exact: true }).focus();
    await page.keyboard.press('Enter');
    assert.equal(await page.locator('.template-layout-tile strong').first().textContent(), 'Utilization table');
    await page.getByRole('button', { name: 'Move Utilization table later', exact: true }).click();
    await page.getByRole('button', { name: 'Make Utilization table half width', exact: true }).click();
    assert.ok(await page.locator('.template-layout-tile').nth(1).evaluate(el => el.classList.contains('half')));
    await page.getByRole('button', { name: 'Make Utilization table full width', exact: true }).click();
    await page.getByRole('button', { name: 'Configure Queue resolved', exact: true }).click();
    await page.getByLabel('Widget title', { exact: true }).first().evaluate(el => { if (document.activeElement !== el) throw new Error('Configure should focus the widget settings'); });
    await page.getByRole('button', { name: 'Save template', exact: true }).click();
    await page.getByRole('button', { name: 'Publish dashboard', exact: true }).waitFor();
    const saved = (await request('/report-templates')).find(item => item.definition.name === name);
    assert.ok(saved); ids.push(saved.id);
    const downloadPromise = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Download JSON', exact: true }).click();
    const download = await downloadPromise;
    const downloadPath = path.join(output, download.suggestedFilename());
    await download.saveAs(downloadPath);
    const exported = JSON.parse(await fs.readFile(downloadPath, 'utf8'));
    assert.deepEqual(exported, saved.definition);
    assert.ok(!('rows' in exported.widgets[0]), 'Export contains bindings, not data');
    await page.getByRole('button', { name: 'Template library', exact: true }).click();
    await page.locator('.template-library-card').filter({ hasText: name }).getByRole('button', { name: 'Open template' }).click();
    await page.locator('.template-result-widget').nth(1).waitFor();
    await page.screenshot({ path: path.join(output, 'template-builder.png'), fullPage: true });
    await page.getByRole('button', { name: 'Template library', exact: true }).click();
    await page.getByLabel('Upload report template JSON').setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from('{broken') });
    await page.getByRole('alert').waitFor();
    await page.getByLabel('Upload report template JSON').setInputFiles(path.resolve(__dirname, '../public/templates/operations-report.json'));
    await page.locator('.template-result-widget').nth(2).waitFor();
    await page.getByLabel('Report name', { exact: true }).fill(`${name} imported`);
    assert.equal(await page.locator('.template-result-widget').count(), 0, 'Edits clear stale preview');
    await page.getByRole('button', { name: 'Save template', exact: true }).click();
    await page.getByRole('button', { name: 'Publish dashboard', exact: true }).waitFor();
    const imported = (await request('/report-templates')).find(item => item.definition.name === `${name} imported`);
    assert.ok(imported); ids.push(imported.id);
    await page.getByRole('button', { name: 'Publish dashboard', exact: true }).click();
    await page.getByRole('button', { name: 'Publish and create link', exact: true }).click();
    const link = page.getByLabel('Shareable dashboard link', { exact: true });
    await link.waitFor();
    const url = await link.inputValue();
    const token = url.split('/').pop();
    publicationId = (await request(`/published-dashboards/token/${token}`)).id;
    const anonymous = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
    const shared = await anonymous.newPage();
    shared.on('pageerror', error => errors.push(error.message));
    await shared.goto(url);
    await shared.getByRole('heading', { name: 'Sign in to your workspace' }).waitFor();
    assert.equal((await shared.request.get(`http://127.0.0.1:8090/api/published-dashboards/token/${token}/data`)).status(), 401);
    await login(shared);
    await shared.locator('.template-result-widget').nth(2).waitFor();
    await request(`/report-templates/${imported.id}`, 'PUT', { ...imported.definition, name: 'Changed after publishing' });
    await shared.reload();
    await shared.locator('.template-report h2').filter({ hasText: `${name} imported` }).waitFor();
    await shared.screenshot({ path: path.join(output, 'published-template.png'), fullPage: true });
    await shared.getByRole('button', { name: 'Toggle theme' }).click();
    await shared.screenshot({ path: path.join(output, 'published-template-dark.png'), fullPage: true });
    await shared.setViewportSize({ width: 390, height: 844 });
    assert.ok(await shared.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Published template fits mobile');
    await shared.screenshot({ path: path.join(output, 'published-template-mobile.png'), fullPage: true });
    await page.getByRole('button', { name: 'Done', exact: true }).click();
    await page.setViewportSize({ width: 390, height: 844 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Template editor fits mobile');
    await page.screenshot({ path: path.join(output, 'template-builder-mobile.png'), fullPage: true });
    await page.getByRole('button', { name: 'Delete template', exact: true }).click();
    await page.getByRole('button', { name: 'Confirm delete', exact: true }).click();
    await page.getByRole('button', { name: 'Create template', exact: true }).waitFor();
    ids.splice(ids.indexOf(imported.id), 1);
    await shared.reload();
    await shared.locator('.template-result-widget').nth(2).waitFor();
    await request(`/published-dashboards/${publicationId}`, 'DELETE'); publicationId = undefined;
    await shared.reload();
    await shared.getByRole('heading', { name: 'Dashboard unavailable' }).waitFor();
    await anonymous.close();
    await page.getByRole('button', { name: 'Create template', exact: true }).click();
    for (let i = 0; i < 12; i++) await page.getByRole('button', { name: 'Add bar chart', exact: true }).click();
    assert.equal(await page.locator('.template-layout-tile').count(), 12, 'Click-to-add works at mobile width');
    assert.ok(await page.getByRole('button', { name: 'Add table', exact: true }).isDisabled(), 'Palette enforces twelve widgets');
    await page.getByRole('button', { name: 'Move Bar chart earlier', exact: true }).last().click();
    assert.equal(await page.locator('.template-layout-tile').count(), 12, 'Reordering is allowed at the limit');
    page.once('dialog', dialog => dialog.accept());
    await page.getByRole('button', { name: 'Template library', exact: true }).click();
    assert.deepEqual(errors, [], 'No browser runtime errors');
    console.log('PASS: drag-and-drop palette and reorder, keyboard moves, mobile add, width controls, 12-widget limit, template builder, chart/table field bindings, database preview, save/open, JSON export/import, invalid upload, stale preview clearing, snapshot publishing, fresh sign-in, delete/revoke, dark mode and mobile.');
  } catch (error) {
    await page.screenshot({ path: path.join(output, 'template-failure.png'), fullPage: true });
    throw error;
  } finally {
    if (publicationId) await request(`/published-dashboards/${publicationId}`, 'DELETE').catch(() => {});
    for (const id of ids) await request(`/report-templates/${id}`, 'DELETE').catch(() => {});
    await browser.close();
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
